// предмет задания, картинка для него - в MissionSprites
enum class MissionKind(val label: String) {
    // обучение
    DOOR("Дверь"),
    CUBES("Кубики"),

    // гостиная
    PICTURE("Картина"),
    PILLOWS("Подушки"),

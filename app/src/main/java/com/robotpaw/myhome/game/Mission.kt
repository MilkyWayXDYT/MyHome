    LAUNDRY("Стирка"),
    CLOTHESPINS("Прищепки"),

    // кухня
    TRASH("Мусор"),
    TABLE("Стол"),
    TEA("Чай"),
    SALAD("Салат"),
    PANCAKES("Блинчики"),

    // финал
    PET_CHOICE("Питомец"),
    PET_TOY("Игрушка"),
    PET_BOWL("Миска"),
    PET_FOOD("Корм")
}

enum class Difficulty(val label: String) {
    NONE(""),
    EASY("лёгкое"),
    MEDIUM("среднее"),
    HARD("сложное")
}

/**
 * Задание в комнате (данные для интерфейса; сама механика лежит в mission/mechanics)
 * @param wallTitle - место в комнате, где стоит предмет
 * @param optional - дополнительная сложность, для прохождения комнаты не обязательно
 * @param instruction - шаги для экрана инструкции
 * @param doneTitle - заголовок экрана результата
 * @param repeatable - false: после выполнения задание больше не запускается (выбор питомца)
 */
data class Mission(
    val id: String,
    val kind: MissionKind,
    val title: String,
    val wallTitle: String,
    val doneTitle: String,
    val difficulty: Difficulty = Difficulty.NONE,
    val optional: Boolean = false,
    val instruction: List<String> = listOf("Здесь будет инструкция к заданию"),
    val repeatable: Boolean = true
)

